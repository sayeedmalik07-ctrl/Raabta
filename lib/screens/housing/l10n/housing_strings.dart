  static const supportedLocales = AppLocale.supportedLocales;

  static String t(String key, [String locale = 'English']) {
    final normalized = AppLocale.normalize(locale);
    final map = _catalog[key];
    if (map == null) return key;
    return map[normalized] ?? map['English'] ?? key;
  }

  static String format(
    String key,
    String locale, {
    required Map<String, String> params,
  }) {
    var value = t(key, locale);
    params.forEach((placeholder, replacement) {
      value = value.replaceAll('{$placeholder}', replacement);
    });
    return value;
  }

  @visibleForTesting
  static Map<String, Set<String>> get localeCoverageReport =>
      buildLocaleCoverageReport(
        catalog: _catalog,
        supportedLocales: supportedLocales,
      );


  static String genderLabel(GenderPreference value, [String locale = 'English']) {
    switch (value) {
      case GenderPreference.maleOnly:
        return t('gender_male_only', locale);
      case GenderPreference.femaleOnly:
        return t('gender_female_only', locale);
      case GenderPreference.family:
        return t('gender_family', locale);
      case GenderPreference.any:
        return t('gender_any', locale);
    }
  }

  static String nationalityLabel(
    NationalityPreference value, [
    String locale = 'English',
  ]) {
    switch (value) {
      case NationalityPreference.any:
        return t('nationality_any', locale);
      case NationalityPreference.indian:
        return t('nationality_indian', locale);
      case NationalityPreference.pakistani:
        return t('nationality_pakistani', locale);
      case NationalityPreference.filipino:
        return t('nationality_filipino', locale);
      case NationalityPreference.arabic:
        return t('nationality_arabic', locale);
    }
  }

  static String listingTypeLabel(ListingType type, [String locale = 'English']) {
    switch (type) {
      case ListingType.all:
        return t('type_all', locale);
      case ListingType.room:
        return t('type_room', locale);
      case ListingType.flat:
        return t('type_flat', locale);
      case ListingType.sharing:
        return t('type_sharing', locale);
      case ListingType.studio:
        return t('type_studio', locale);
    }
  }

  static String furnishedLabel(bool furnished, [String locale = 'English']) =>
      t(furnished ? 'furnished_yes' : 'furnished_no', locale);

  static String postedLabel(int daysAgo, [String locale = 'English']) {
    if (daysAgo <= 0) return t('posted_today', locale);
    if (daysAgo == 1) return t('posted_yesterday', locale);
    return format('posted_days_ago', locale, params: {'days': '$daysAgo'});
  }

  static String listingStatusLabel(ListingStatus status, [String locale = 'English']) {
    switch (status) {
      case ListingStatus.pending:
        return t('listing_status_pending', locale);
      case ListingStatus.approved:
        return t('listing_status_approved', locale);
      case ListingStatus.rejected:
        return t('listing_status_rejected', locale);
    }
  }

  static String filterTypeLabel(ListingType type, [String locale = 'English']) {
    switch (type) {
      case ListingType.all:
        return t('filter_all', locale);
      case ListingType.room:
        return t('filter_room', locale);
      case ListingType.flat:
        return t('filter_flat', locale);
      case ListingType.sharing:
        return t('filter_sharing', locale);
      case ListingType.studio:
        return t('filter_studio', locale);
    }
  }

  static String scamVerdictLabel(ScamVerdict verdict, [String locale = 'English']) {
    switch (verdict) {
      case ScamVerdict.safe:
        return t('scam_verified_safe', locale);
      case ScamVerdict.suspicious:
        return t('scam_review_carefully', locale);
      case ScamVerdict.likelyScam:
        return t('scam_possible_scam', locale);
    }
  }

