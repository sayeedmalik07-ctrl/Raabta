import 'dart:io';

import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:share_plus/share_plus.dart';
import 'package:raabta/features/trip_planner/domain/models/trip_plan.dart';
import 'package:raabta/features/trip_planner/presentation/l10n/trip_strings.dart';

class TripPdfService {
  Future<File> generateReport({
    required TripPlan trip,
    required String locale,
  }) async {
    final doc = pw.Document();
    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              'RAABTA — ${trip.title}',
              style: pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Text(
            'Qatar Travel Itinerary · ${trip.totalDays} days',
            style: const pw.TextStyle(fontSize: 12),
          ),
          pw.SizedBox(height: 8),
          pw.Text(
            '${TripStrings.t('trip_budget', locale)}: '
            '${formatTripCurrency(trip.budget.totalSpent, symbol: trip.preferences.currency)}',
          ),
          pw.SizedBox(height: 16),
          ...trip.days.expand((day) sync* {
            yield pw.Text(
              day.title,
              style: pw.TextStyle(
                fontSize: 14,
                fontWeight: pw.FontWeight.bold,
              ),
            );
            yield pw.SizedBox(height: 6);
            for (final act in day.activities) {
              yield pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 4, left: 8),
                child: pw.Text(
                  '${act.startTime} — ${act.title} (${act.durationMinutes} min)',
                ),
              );
            }
            yield pw.SizedBox(height: 12);
          }),
          pw.SizedBox(height: 12),
          pw.Text(
            'Emergency: 999 · MOI: 109',
            style: const pw.TextStyle(fontSize: 10),
          ),
          pw.Text(
            'Generated by RAABTA Trip Planner',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ],
      ),
    );

    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/raabta_trip_${trip.id}.pdf',
    );
    await file.writeAsBytes(await doc.save());
    return file;
  }

  Future<void> sharePdf(File file) async {
    await Share.shareXFiles([XFile(file.path)], text: 'My Qatar trip — RAABTA');
  }
}

final tripPdfServiceProvider = Provider<TripPdfService>((ref) {
  return TripPdfService();
});
