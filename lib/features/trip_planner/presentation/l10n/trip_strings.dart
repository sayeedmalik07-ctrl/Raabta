  static String t(String key, [String locale = 'English']) {
    final normalized = AppLocale.normalize(locale);
    final map = _catalog[key];
    if (map == null) return key;
    return map[normalized] ?? map['English'] ?? key;
  }

  static String format(
    String key,
    String locale,
    Map<String, String> params,
  ) {
    var text = t(key, locale);
    for (final entry in params.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value);
    }
    return text;
  }

  static String transportMetroTip1(String locale) => format(
        'transport_metro_tip1',
        locale,
        DohaTransitFaresConfig.standardMetroCopyParams(),
      );

  static String transportCostsBody(String locale) => format(
        'transport_costs_body',
        locale,
        DohaTransitFaresConfig.standardMetroCopyParams(),
      );

  static String resolveTransportCopy(String key, String locale) {
    switch (key) {
      case 'transport_metro_tip1':
        return transportMetroTip1(locale);
      case 'transport_costs_body':
        return transportCostsBody(locale);
      default:
        return t(key, locale);
    }
  }

