String formatTripCurrency(double amount, {String symbol = 'QAR'}) {
  final formatted = amount.toStringAsFixed(0).replaceAllMapped(
        RegExp(r'(\d{1,3})(?=(\d{3})+(?!\d))'),
        (m) => '${m[1]},',
      );
  return '$symbol $formatted';
}
