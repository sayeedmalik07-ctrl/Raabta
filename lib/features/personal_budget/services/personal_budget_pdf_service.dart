import 'dart:io';

import 'package:intl/intl.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:raabta/features/personal_budget/services/personal_budget_report_service.dart';

class PersonalBudgetPdfService {
  Future<File> generateReport(PersonalBudgetReport report) async {
    final doc = pw.Document();
    final dateLabel = DateFormat.yMMMMd().format(report.generatedAt);

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              report.title,
              style: pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Text('RAABTA Money Hub · $dateLabel'),
          pw.SizedBox(height: 20),
          for (final section in report.sections) ...[
            pw.Text(
              section.heading,
              style: pw.TextStyle(
                fontSize: 14,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 6),
            pw.Text(section.body, style: const pw.TextStyle(fontSize: 11)),
            if (section.bullets.isNotEmpty) ...[
              pw.SizedBox(height: 6),
              for (final bullet in section.bullets)
                pw.Bullet(text: bullet, style: const pw.TextStyle(fontSize: 10)),
            ],
            pw.SizedBox(height: 16),
          ],
          pw.Divider(),
          pw.Text(
            'Generated by RAABTA Personal Budget — not financial advice.',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ],
      ),
    );

    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/raabta_budget_${report.generatedAt.millisecondsSinceEpoch}.pdf',
    );
    await file.writeAsBytes(await doc.save());
    return file;
  }
}
