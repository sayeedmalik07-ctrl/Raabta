import 'dart:io';

import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:share_plus/share_plus.dart';
import 'package:raabta/features/prayer_mosque/data/islamic_content_repository.dart';
import 'package:raabta/features/prayer_mosque/domain/models/prayer_schedule.dart';
import 'package:raabta/features/prayer_mosque/presentation/l10n/prayer_strings.dart';
import 'package:raabta/features/ramadan/hijri_calendar.dart';

class PrayerPdfService {
  Future<File> generateDailySchedule({
    required PrayerScheduleDay schedule,
    required String locale,
    required bool use24Hour,
  }) async {
    final doc = pw.Document();
    final fmt = use24Hour ? DateFormat.Hm() : DateFormat.jm();
    final hijri = gregorianToHijri(schedule.date);
    final monthName =
        IslamicContentRepository.hijriMonthNames[hijri.month] ?? '';

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              'RAABTA — ${PrayerStrings.t('prayer_times', locale)}',
              style: pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Text('${schedule.locationLabel} · Qatar'),
          pw.Text('$monthName ${hijri.day}, ${hijri.year} AH'),
          pw.Text(DateFormat.yMMMMEEEEd().format(schedule.date)),
          pw.SizedBox(height: 16),
          ...schedule.entries.map(
            (e) => pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 6),
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(PrayerStrings.t(e.labelKey, locale)),
                  pw.Text(fmt.format(e.time)),
                ],
              ),
            ),
          ),
          pw.SizedBox(height: 24),
          pw.Text(
            'Generated by RAABTA Islamic Companion',
            style: const pw.TextStyle(fontSize: 10),
          ),
        ],
      ),
    );

    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/raabta_prayer_${schedule.date.millisecondsSinceEpoch}.pdf',
    );
    await file.writeAsBytes(await doc.save());
    return file;
  }

  Future<void> sharePdf(File file) async {
    await Share.shareXFiles([XFile(file.path)], text: 'RAABTA Prayer Schedule');
  }
}

final prayerPdfServiceProvider = Provider<PrayerPdfService>((ref) {
  return PrayerPdfService();
});
