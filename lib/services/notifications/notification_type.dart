/// Metadata for each [NotificationType] — taxonomy, priority, quiet-hours rules.
class NotificationTypeMeta {
  const NotificationTypeMeta({
    required this.type,
    required this.apiKey,
    required this.group,
    required this.highPriority,
    required this.quietHoursExemptByDefault,
    required this.defaultEnabled,
    required this.userCanDisable,
    required this.dedupTtlHours,
    required this.dailyCap,
    required this.l10nKey,
    this.defaultPriority = NotificationPriority.p3UsefulRecommendation,
    this.maxPriority = NotificationPriority.p3UsefulRecommendation,
    this.promotionalCommercial = false,
  });

  final NotificationType type;
  final String apiKey;
  final NotificationCategoryGroup group;
  final bool highPriority;
  final bool quietHoursExemptByDefault;
  final bool defaultEnabled;
  final bool userCanDisable;
  final int dedupTtlHours;
  final int dailyCap;
  final String l10nKey;
  final NotificationPriority defaultPriority;
  final NotificationPriority maxPriority;
  final bool promotionalCommercial;
}

